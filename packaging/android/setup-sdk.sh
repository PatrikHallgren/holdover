#!/bin/sh
# Install the Android SDK and NDK this companion builds with.
# Java must already be on PATH. On Omarchy, mise can provide it:
#   mise install java@temurin-21
#   export JAVA_HOME="$(mise where java@temurin-21)"
#   mise exec rust@1.98.1 -- bash packaging/android/setup-sdk.sh
# A distro JDK is the same idea:
#   sudo pacman -S --needed jdk21-openjdk
#   export JAVA_HOME=/usr/lib/jvm/java-21-openjdk
set -eu

SDK_ROOT="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-$HOME/Android/Sdk}}"
NDK_VERSION="${HOLDOVER_NDK_VERSION:-29.0.13846066}"
CMDLINE_ZIP="${HOLDOVER_CMDLINE_ZIP:-commandlinetools-linux-13114758_latest.zip}"
CMDLINE_URL="${HOLDOVER_CMDLINE_URL:-https://dl.google.com/android/repository/$CMDLINE_ZIP}"

if ! command -v java >/dev/null 2>&1; then
  echo "java is not on PATH. Install a JDK 21 and set JAVA_HOME, then run this again." >&2
  exit 1
fi
if [ -z "${JAVA_HOME:-}" ]; then
  echo "JAVA_HOME is not set. Point it at the JDK 21 home, then run this again." >&2
  exit 1
fi

mkdir -p "$SDK_ROOT"
if [ ! -x "$SDK_ROOT/cmdline-tools/bin/sdkmanager" ] && [ ! -x "$SDK_ROOT/cmdline-tools/latest/bin/sdkmanager" ]; then
  tmp="$(mktemp -d)"
  echo "Downloading Android command line tools..."
  curl -fsSL "$CMDLINE_URL" -o "$tmp/cmdtools.zip"
  unzip -q "$tmp/cmdtools.zip" -d "$SDK_ROOT"
  rm -rf "$tmp"
fi

if [ -x "$SDK_ROOT/cmdline-tools/latest/bin/sdkmanager" ]; then
  SDKMANAGER="$SDK_ROOT/cmdline-tools/latest/bin/sdkmanager"
elif [ -x "$SDK_ROOT/cmdline-tools/bin/sdkmanager" ]; then
  SDKMANAGER="$SDK_ROOT/cmdline-tools/bin/sdkmanager"
else
  echo "sdkmanager was not found under $SDK_ROOT/cmdline-tools" >&2
  exit 1
fi

yes | "$SDKMANAGER" --sdk_root="$SDK_ROOT" --licenses >/dev/null || true
"$SDKMANAGER" --sdk_root="$SDK_ROOT" --install \
  "platform-tools" \
  "platforms;android-36" \
  "build-tools;36.0.0" \
  "ndk;$NDK_VERSION"

env_file="${XDG_CONFIG_HOME:-$HOME/.config}/holdover/android-env.sh"
mkdir -p "$(dirname "$env_file")"
cat >"$env_file" <<EOF
# Generated by packaging/android/setup-sdk.sh. Source this before an APK build.
export JAVA_HOME="${JAVA_HOME}"
export ANDROID_HOME="${SDK_ROOT}"
export ANDROID_SDK_ROOT="${SDK_ROOT}"
export NDK_HOME="${SDK_ROOT}/ndk/${NDK_VERSION}"
export PATH="\$ANDROID_HOME/platform-tools:\$PATH"
EOF

if command -v rustup >/dev/null 2>&1; then
  rustup target add aarch64-linux-android
fi

echo "Android SDK is at $SDK_ROOT"
echo "Source $env_file before packaging/android/build-apk.sh"
